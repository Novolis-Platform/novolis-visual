using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using Novolis.Visual.Compile;
using Novolis.Visual.Definitions;

namespace Novolis.Visual.CodeGen;

/// <summary>
/// Emits readable C# with no dependency on the authoring graph or compiler.
/// </summary>
public sealed class VisualCSharpGenerator
{
    public GeneratedVisualSource Generate(
        VisualIR compilation,
        VisualCodeGenerationOptions? options = null)
    {
        ArgumentNullException.ThrowIfNull(compilation);
        options ??= new VisualCodeGenerationOptions();
        options.Validate();
        if (!compilation.Success)
        {
            throw new InvalidOperationException(
                "A valid compilation is required before code generation.");
        }

        var ir = compilation;
        var typeName = SanitizeIdentifier(options.TypeName, "GeneratedVisual");
        var ns = SanitizeNamespace(options.Namespace);
        var source = EmitSource(ir, ns, typeName, options.Mode);
        var hash = Convert.ToHexString(
            SHA256.HashData(Encoding.UTF8.GetBytes(source)));
        return new GeneratedVisualSource
        {
            Source = source,
            RecipeFingerprint = ir.SemanticFingerprint,
            Mode = options.Mode,
            TypeName = typeName,
            SourceSha256 = hash,
        };
    }

    private static string EmitSource(
        VisualIR ir,
        string @namespace,
        string typeName,
        VisualCodeGenerationMode mode)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.Append("namespace ").Append(@namespace).AppendLine(";");
        builder.AppendLine();
        builder.Append("public static class ").Append(typeName).AppendLine();
        builder.AppendLine("{");
        builder.Append("    public const string RecipeFingerprint = \"")
            .Append(Escape(ir.SemanticFingerprint))
            .AppendLine("\";");
        builder.Append("    public const int NodeCount = ")
            .Append(ir.Nodes.Length.ToString(CultureInfo.InvariantCulture))
            .AppendLine(";");
        builder.AppendLine();
        builder.AppendLine("    public static double EvaluateScalar(");
        builder.AppendLine("        double x, double y, double z, double time = 0d)");
        builder.AppendLine("    {");
        var variables = ir.Nodes
            .Select((node, index) => (node, Name: $"value{index}"))
            .ToDictionary(item => item.node.Id, item => item.Name);
        foreach (var item in ir.Nodes.Select((node, index) => (node, index)))
        {
            builder.Append("        var value")
                .Append(item.index.ToString(CultureInfo.InvariantCulture))
                .Append(" = ")
                .Append(EmitExpression(item.node, variables))
                .AppendLine(";");
        }

        var output = ir.Outputs.FirstOrDefault();
        if (output is not null &&
            variables.TryGetValue(output.SourceNodeId, out var outputVariable))
        {
            builder.Append("        return ").Append(outputVariable).AppendLine(";");
        }
        else if (ir.Nodes.Length > 0)
        {
            builder.Append("        return value")
                .Append((ir.Nodes.Length - 1).ToString(CultureInfo.InvariantCulture))
                .AppendLine(";");
        }
        else
        {
            builder.AppendLine("        return 0d;");
        }

        builder.AppendLine("    }");
        builder.AppendLine();
        builder.Append("    public static string Mode => \"")
            .Append(mode)
            .AppendLine("\";");
        if (mode == VisualCodeGenerationMode.Builder)
        {
            builder.AppendLine();
            builder.AppendLine("    public static string Describe() =>");
            builder.AppendLine("        $\"{RecipeFingerprint}:{NodeCount}\";");
        }
        else if (mode == VisualCodeGenerationMode.EmbeddedPayload)
        {
            builder.AppendLine();
            builder.AppendLine("    public static byte[] FingerprintBytes =>");
            builder.AppendLine("        global::System.Convert.FromHexString(RecipeFingerprint);");
        }

        builder.AppendLine();
        builder.AppendLine("    private static double Noise(");
        builder.AppendLine("        double x, double y, double z, double time)");
        builder.AppendLine("    {");
        builder.AppendLine("        var value = global::System.Math.Sin(");
        builder.AppendLine("            x * 12.9898d + y * 78.233d + z * 37.719d + time * 11.137d) *");
        builder.AppendLine("            43758.5453d;");
        builder.AppendLine("        return value - global::System.Math.Floor(value);");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string EmitExpression(
        VisualIRNode node,
        IReadOnlyDictionary<NodeId, string> variables)
    {
        var inputs = node.Inputs
            .Select(input => variables.TryGetValue(input.SourceNodeId, out var variable)
                ? variable
                : "0d")
            .ToArray();
        var left = inputs.ElementAtOrDefault(0) ?? "0d";
        var right = inputs.ElementAtOrDefault(1) ?? "0d";

        if (node.ConstantValue is ScalarValue scalar)
        {
            return scalar.Value.ToString("R", CultureInfo.InvariantCulture) + "d";
        }

        return node.Operation switch
        {
            "add.scalar" => $"({left} + {right})",
            "multiply.scalar" => $"({left} * {right})",
            "noise.scalar" => "Noise(x, y, z, time)",
            _ => "0d",
        };
    }

    private static string SanitizeIdentifier(string value, string fallback)
    {
        var chars = value
            .Where(character => char.IsLetterOrDigit(character) || character == '_')
            .ToArray();
        var result = chars.Length == 0 ? fallback : new string(chars);
        return char.IsLetter(result[0]) || result[0] == '_'
            ? result
            : "_" + result;
    }

    private static string SanitizeNamespace(string value) =>
        string.Join(
            ".",
            value.Split('.', StringSplitOptions.RemoveEmptyEntries)
                .Select(segment => SanitizeIdentifier(segment, "Generated")));

    private static string Escape(string value) =>
        value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal);
}
