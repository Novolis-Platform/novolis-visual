using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using Novolis.Visual.Definitions;

namespace Novolis.Visual.CodeGen;

/// <summary>
/// Emits self-contained C# for decoded images and their sprite metadata.
/// </summary>
public sealed class VisualImageCodeGenerator
{
    public GeneratedVisualSource Generate(
        IEnumerable<VisualImageAsset> assets,
        string namespaceName = "Generated.Visuals",
        string typeName = "GeneratedImages")
    {
        ArgumentNullException.ThrowIfNull(assets);
        var ordered = assets
            .OrderBy(asset => asset.AssetId, StringComparer.Ordinal)
            .ToArray();
        if (ordered.Length == 0)
        {
            throw new ArgumentException(
                "At least one image asset is required.",
                nameof(assets));
        }

        var fingerprint = CreateFingerprint(ordered);
        var source = EmitSource(
            ordered,
            SanitizeNamespace(namespaceName),
            SanitizeIdentifier(typeName, "GeneratedImages"),
            fingerprint);
        return new GeneratedVisualSource
        {
            Source = source,
            RecipeFingerprint = fingerprint,
            Mode = VisualCodeGenerationMode.EmbeddedPayload,
            TypeName = SanitizeIdentifier(typeName, "GeneratedImages"),
            SourceSha256 = Convert.ToHexString(
                SHA256.HashData(Encoding.UTF8.GetBytes(source))),
        };
    }

    private static string EmitSource(
        IReadOnlyList<VisualImageAsset> assets,
        string namespaceName,
        string typeName,
        string fingerprint)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.Append("namespace ").Append(namespaceName).AppendLine(";");
        builder.AppendLine();
        builder.Append("public static class ").Append(typeName).AppendLine();
        builder.AppendLine("{");
        builder.Append("    public const string Fingerprint = \"")
            .Append(fingerprint)
            .AppendLine("\";");
        builder.AppendLine();
        builder.AppendLine("    public sealed record Frame(");
        builder.AppendLine("        string Name,");
        builder.AppendLine("        int X,");
        builder.AppendLine("        int Y,");
        builder.AppendLine("        int Width,");
        builder.AppendLine("        int Height,");
        builder.AppendLine("        double PivotX,");
        builder.AppendLine("        double PivotY,");
        builder.AppendLine("        double DurationSeconds);");
        builder.AppendLine();
        builder.AppendLine("    public sealed record ImageAsset(");
        builder.AppendLine("        string Id,");
        builder.AppendLine("        int Width,");
        builder.AppendLine("        int Height,");
        builder.AppendLine("        byte[] Pixels,");
        builder.AppendLine("        Frame[] Frames);");
        builder.AppendLine();
        builder.AppendLine("    public static ImageAsset[] Assets { get; } =");
        builder.AppendLine("    [");
        foreach (var asset in assets)
        {
            builder.Append("        new ImageAsset(\"")
                .Append(Escape(asset.AssetId))
                .Append("\", ")
                .Append(asset.Width.ToString(CultureInfo.InvariantCulture))
                .Append(", ")
                .Append(asset.Height.ToString(CultureInfo.InvariantCulture))
                .AppendLine(",");
            builder.AppendLine("            new byte[]");
            builder.AppendLine("            {");
            AppendBytes(builder, asset.RgbaPixels);
            builder.AppendLine("            },");
            builder.AppendLine("            new Frame[]");
            builder.AppendLine("            {");
            foreach (var frame in asset.Frames)
            {
                builder.Append("                new Frame(\"")
                    .Append(Escape(frame.Name))
                    .Append("\", ")
                    .Append(frame.X.ToString(CultureInfo.InvariantCulture))
                    .Append(", ")
                    .Append(frame.Y.ToString(CultureInfo.InvariantCulture))
                    .Append(", ")
                    .Append(frame.Width.ToString(CultureInfo.InvariantCulture))
                    .Append(", ")
                    .Append(frame.Height.ToString(CultureInfo.InvariantCulture))
                    .Append(", ")
                    .Append(frame.PivotX.ToString("R", CultureInfo.InvariantCulture))
                    .Append(", ")
                    .Append(frame.PivotY.ToString("R", CultureInfo.InvariantCulture))
                    .Append(", ")
                    .Append(frame.DurationSeconds.ToString("R", CultureInfo.InvariantCulture))
                    .AppendLine("),");
            }

            builder.AppendLine("            }),");
        }

        builder.AppendLine("    ];");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void AppendBytes(
        StringBuilder builder,
        IEnumerable<byte> bytes)
    {
        var index = 0;
        foreach (var value in bytes)
        {
            if (index % 16 == 0)
            {
                builder.Append("                ");
            }

            builder.Append("0x")
                .Append(value.ToString("X2", CultureInfo.InvariantCulture))
                .Append(", ");
            index++;
            if (index % 16 == 0)
            {
                builder.AppendLine();
            }
        }

        if (index % 16 != 0)
        {
            builder.AppendLine();
        }
    }

    private static string CreateFingerprint(
        IEnumerable<VisualImageAsset> assets)
    {
        using var stream = new MemoryStream();
        using var writer = new BinaryWriter(stream, Encoding.UTF8, leaveOpen: true);
        foreach (var asset in assets)
        {
            writer.Write(asset.AssetId);
            writer.Write(asset.Width);
            writer.Write(asset.Height);
            writer.Write(asset.SourceSha256);
            writer.Write(asset.RgbaPixels.Length);
            writer.Write(asset.RgbaPixels.ToArray());
            foreach (var frame in asset.Frames)
            {
                writer.Write(frame.Name);
                writer.Write(frame.X);
                writer.Write(frame.Y);
                writer.Write(frame.Width);
                writer.Write(frame.Height);
                writer.Write(frame.PivotX);
                writer.Write(frame.PivotY);
                writer.Write(frame.DurationSeconds);
            }
        }

        writer.Flush();
        return Convert.ToHexString(
                SHA256.HashData(stream.ToArray()))
            .ToLowerInvariant();
    }

    private static string SanitizeIdentifier(string value, string fallback)
    {
        var chars = value
            .Where(character => char.IsLetterOrDigit(character) || character == '_')
            .ToArray();
        var result = chars.Length == 0 ? fallback : new string(chars);
        return char.IsLetter(result[0]) || result[0] == '_'
            ? result
            : "_" + result;
    }

    private static string SanitizeNamespace(string value) =>
        string.Join(
            ".",
            value.Split('.', StringSplitOptions.RemoveEmptyEntries)
                .Select(segment => SanitizeIdentifier(segment, "Generated")));

    private static string Escape(string value) =>
        value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal);
}
